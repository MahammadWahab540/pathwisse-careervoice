  select
    r.id as role_id,
    u.domains,
    u.preferred_interests,
    u.problem_types,
    u.work_styles,
    u.environments,
    u.preferred_evidence,
    u.prerequisites,
    u.anti_signals,
    coalesce(jsonb_agg(adj.id order by adj.title) filter (where adj.id is not null), '[]'::jsonb) as adjacent_role_ids,
    u.transition_difficulty,
    u.market_demand_score
  from genome_updates u
  join public.career_roles r on r.title = u.title and r.status = 'published'
  left join lateral jsonb_array_elements_text(u.adjacent_titles) adjacent_title(title) on true
  left join public.career_roles adj on adj.title = adjacent_title.title and adj.status = 'published'
  group by r.id, u.domains, u.preferred_interests, u.problem_types, u.work_styles, u.environments, u.preferred_evidence, u.prerequisites, u.anti_signals, u.transition_difficulty, u.market_demand_score
