declare
  missing_count integer;
begin
  select count(*)
  into missing_count
  from public.career_roles r
  left join public.career_role_genomes g on g.role_id = r.id and g.status = 'published'
  where r.status = 'published'
    and (
      g.role_id is null
      or jsonb_array_length(g.anti_signals) = 0
      or jsonb_array_length(g.adjacent_role_ids) = 0
      or jsonb_array_length(g.preferred_interests) = 0
      or jsonb_array_length(g.problem_types) = 0
      or jsonb_array_length(g.work_styles) = 0
      or jsonb_array_length(g.environments) = 0
      or jsonb_array_length(g.preferred_evidence) = 0
      or jsonb_array_length(g.prerequisites) = 0
    );

  if missing_count > 0 then
    raise exception 'career_intelligence_v2_genome_intelligence incomplete for % published roles', missing_count;
  end if;
end $$;

